#!/usr/bin/env python3
"""Generate deterministic, original repair fixtures. Does not run Orca or build anything."""

import argparse
import json
from pathlib import Path


VERTICES = [(0, 0, 0), (10, 0, 0), (10, 10, 0), (0, 10, 0),
            (0, 0, 10), (10, 0, 10), (10, 10, 10), (0, 10, 10)]
FACES = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
         (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]


def generate(destination):
    destination.mkdir(parents=True, exist_ok=True)
    cases = []

    def add(name, vertices, faces, expected, description, *, volume=None, colored=False):
        obj = ["# Original deterministic Orca repair test fixture; coordinates in mm."]
        if colored:
            obj.append("mtllib colors.mtl")
        obj += ["v " + " ".join(f"{n:.9g}" for n in v) for v in vertices]
        for index, face in enumerate(faces):
            if colored:
                obj.append("usemtl " + ("red" if index < 4 else "green"))
            obj.append("f " + " ".join(str(n + 1) for n in face))
        (destination / f"{name}.obj").write_text("\n".join(obj) + "\n", encoding="utf-8")
        # The current ADMesh probe reads 128 bytes after the 84-byte header.
        # Keep even a one-facet ASCII fixture long enough to reach mesh repair.
        solid_name = name + ("-single-facet-import-probe" if len(faces) == 1 else "")
        stl = [f"solid {solid_name}"]
        for face in faces:
            stl += ["  facet normal 0 0 0", "    outer loop"]
            stl += ["      vertex " + " ".join(f"{n:.9g}" for n in vertices[i]) for i in face]
            stl += ["    endloop", "  endfacet"]
        stl.append(f"endsolid {solid_name}")
        (destination / f"{name}.stl").write_text("\n".join(stl) + "\n", encoding="ascii")
        cases.append(dict(name=name, expected=expected, description=description, facets=len(faces),
                          expected_volume_mm3=volume, colored=colored))

    add("00-healthy-cube", VERTICES, FACES, "success", "健康基准：10 mm 立方体，无需改变。", volume=1000)
    add("01-missing-top", VERTICES, FACES[:2] + FACES[4:], "success", "删除顶面两个三角形；应补洞。", volume=1000)
    cracked = list(FACES)
    cracked[0] = (8, 2, 1)
    add("02-small-crack", VERTICES + [(0.00001, 0, 0)], cracked, "success",
        "一个角在单面中错开 0.00001 mm；应近邻合缝，不增加面。", volume=1000)
    reversed_faces = [(c, b, a) if i in (0, 3, 7) else (a, b, c) for i, (a, b, c) in enumerate(FACES)]
    add("03-wrong-winding", VERTICES, reversed_faces, "success", "三处面朝向反转；应统一实体朝向。", volume=1000)
    add("04-duplicate-face", VERTICES, FACES + [FACES[0]], "success", "重复底面，边出现多重连接；应去重。", volume=1000)
    add("05-degenerate-face", VERTICES + [(20, 0, 0)], FACES + [(0, 1, 8), (0, 0, 1)], "success",
        "增加共线零面积面与重复顶点面；应清理。", volume=1000)
    add("06-isolated-face", VERTICES + [(2, 2, 5), (4, 2, 5), (2, 4, 5)], FACES + [(8, 9, 10)], "success",
        "实体内部有一个没有边邻居的孤立面；应清理，不封成薄壳。", volume=1000)
    thin = [(12 + x, y, z * 0.0001) for x, y, z in VERTICES]
    add("07-thin-solid", VERTICES + thin, FACES + [tuple(i + 8 for i in f) for f in FACES], "success",
        "独立 0.001 mm 薄实体必须保留；该厚度可能无法用实际层高打印，几何通过不等于可打印。", volume=1000.1)
    overlap = [(x + 5, y, z) for x, y, z in VERTICES]
    add("08-intersecting-shells", VERTICES + overlap, FACES + [tuple(i + 8 for i in f) for f in FACES], "failure",
        "两个实体大范围相交；不自动布尔重建，必须拒绝并保留原模型。")
    tetra = [(0, 0, 0), (10, 0, 0), (0, 10, 0), (0, 0, 10), (0, -10, 0), (0, 0, -10)]
    faces = [(0, 2, 1), (0, 1, 3), (0, 3, 2), (1, 2, 3),
             (0, 4, 1), (0, 1, 5), (0, 5, 4), (1, 4, 5)]
    add("09-nonmanifold-edge", tetra, faces, "failure", "四个面共用一条边；拆分后仍几何接触，必须安全拒绝。")
    add("10-only-triangle", [(0, 0, 0), (10, 0, 0), (0, 10, 0)], [(0, 1, 2)], "failure",
        "只有单个平面，不存在可保留实体；不得声称修复成功。")
    add("11-colored-missing-top", VERTICES, FACES[:2] + FACES[4:], "success",
        "红绿 MTL 面颜色加缺顶面；保留旧面的颜色，新增面采用所属部件默认色，不推断花纹。",
        volume=1000, colored=True)
    (destination / "colors.mtl").write_text("newmtl red\nKd 1 0 0\nnewmtl green\nKd 0 1 0\n", encoding="ascii")
    (destination / "12-invalid-index.obj").write_text("v 0 0 0\nv 10 0 0\nv 0 10 0\nf 1 2 99\n", encoding="ascii")
    cases.append(dict(name="12-invalid-index", expected="failure", description="OBJ 越界索引，应在导入阶段拒绝。",
                      facets=1, expected_volume_mm3=None, colored=False, formats=["obj"]))
    (destination / "manifest.json").write_text(json.dumps({
        "schema_version": 1, "source": "Original synthetic fixtures generated by scripts/generate_repair_fixtures.py",
        "note": "Expected results are acceptance criteria, NOT a record of tests having passed.",
        "cases": cases,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Generated {len(cases)} fixture cases in {destination.resolve()}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "tests/data/model_repair_acceptance")
    args = parser.parse_args()
    generate(args.output)
